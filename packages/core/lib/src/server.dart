/// LAN HTTP API for Eleen: the sync surface between the TV and the parent
/// phone app.
///
/// [EleenServer] binds a real socket and dispatches to [EngineCoordinator],
/// which owns the [EleenDatabase] and the pure [TimeEngine]. Auth model:
///
/// - Every route except `POST /api/pair` requires `Authorization: Bearer
///   <token>`; the token is issued by a successful pair and stored in the
///   settings table. Missing or wrong token -> 401.
/// - Every mutating route additionally requires the parent PIN in the JSON
///   body (`pin` field); wrong or missing PIN -> 403. The exception is
///   `PUT /api/pin` itself, which provisions/changes the PIN (it needs no
///   PIN while none is set, and the current PIN to change an existing one).
/// - The parent PIN is OPTIONAL: while no PIN has been provisioned
///   (`Settings.parentPin` empty), the PIN check is skipped entirely and any
///   `pin` value (or its absence) is accepted. The wire contract is
///   unchanged — a client that always sends a `pin` field behaves the same
///   under both shapes; once a PIN is set, every gate enforces it as before.
/// - Pairing nonces are generated by the TV pairing screen via
///   [PairingCodec.newNonce] and registered with [EleenServer.registerNonce];
///   each nonce is single-use.
library eleen_core.server;

import 'dart:convert';
import 'dart:io';
import 'dart:math';

import 'db.dart';
import 'models.dart';
import 'time_engine.dart';

/// Encodes and decodes the `eleen://pair?host=..&port=..&nonce=..` QR/NFC
/// payload the TV shows the parent app during pairing.
abstract final class PairingCodec {
  /// Generates a fresh single-use pairing nonce.
  static String newNonce() => randomHex(16);

  /// Builds the pairing payload for a TV listening on [host]:[port].
  static String payload({
    required String host,
    required int port,
    required String nonce,
  }) =>
      'eleen://pair?host=$host&port=$port&nonce=$nonce';

  /// Parses a pairing payload, or returns null if it is not a valid
  /// `eleen://pair` URI with all three parameters present.
  static ({String host, int port, String nonce})? parse(String payload) {
    final uri = Uri.tryParse(payload);
    if (uri == null || uri.scheme != 'eleen' || uri.host != 'pair') {
      return null;
    }
    final host = uri.queryParameters['host'];
    final nonce = uri.queryParameters['nonce'];
    final port =
        uri.queryParameters.containsKey('port') ? int.tryParse(uri.queryParameters['port']!) : null;
    if (host == null || host.isEmpty || port == null || nonce == null || nonce.isEmpty) {
      return null;
    }
    return (host: host, port: port, nonce: nonce);
  }
}

/// Cryptographically random lowercase-hex string from [bytes] random bytes.
String randomHex(int bytes) {
  final random = Random.secure();
  return List.generate(
    bytes,
    (_) => random.nextInt(256).toRadixString(16).padLeft(2, '0'),
  ).join();
}

/// Owns the database and the (pure) [TimeEngine] and exposes the operations
/// the HTTP layer is a thin shell over.
///
/// Per-session reminder-threshold bookkeeping (the "fired set") lives here,
/// because the engine is pure by design: [markThresholdFired] records a fire,
/// [addTime] re-arms entries below the new remaining time.
class EngineCoordinator {
  EngineCoordinator({required EleenDatabase db, required TimeEngine engine})
      : db = db,
        engine = engine;

  final EleenDatabase db;
  final TimeEngine engine;

  /// profileId -> thresholds (in session seconds) already fired for it.
  final Map<String, Set<int>> _fired = {};

  /// Records that [thresholdSec] fired for [profileId], suppressing repeats.
  void markThresholdFired(String profileId, int thresholdSec) {
    _fired.putIfAbsent(profileId, () => {}).add(thresholdSec);
  }

  /// The fired thresholds for [profileId]; do not modify.
  Set<int> firedThresholds(String profileId) =>
      Set.unmodifiable(_fired[profileId] ?? const {});

  /// Re-arms thresholds after time was added: entries below [remainingSec]
  /// can fire again and are cleared.
  void rearmThresholds(String profileId, int remainingSec) {
    _fired[profileId]?.removeWhere((t) => t < remainingSec);
  }

  /// Whether the TV app currently holds the SYSTEM_ALERT_WINDOW permission.
  /// Not persisted — the TV app updates this from a live platform check
  /// (see TvHome's permission probe) and it is surfaced to phones in
  /// [state] so the parent dashboard can warn when the TV can't lock.
  bool overlayPermissionGranted = true;

  /// Current TV state. Remaining times are derived from CURRENT profiles
  /// only, so sessions orphaned by deleteProfile are never surfaced.
  /// Includes each current profile's daily usage (v1.1 D): today's used
  /// seconds plus the last 14 days of history.
  Future<TvState> state() async {
    final profiles = await db.allProfiles();
    final today = engine.clock.today();
    final settings = await db.getSettings();

    String? activeProfileId;
    final remainingByProfile = <String, int>{};
    final usageByProfile = <String, ProfileUsage>{};
    SessionState? activeSession;
    for (final p in profiles) {
      final session = await db.sessionForProfile(p.id, today);
      remainingByProfile[p.id] =
          session?.remainingSeconds ?? p.allowance.minutes * 60;
      usageByProfile[p.id] = ProfileUsage(
        todaySeconds: await db.usedSecondsFor(p.id, today),
        history: await db.usageHistory(p.id),
      );
      if (session != null && session.active && activeProfileId == null) {
        activeProfileId = p.id;
        activeSession = session;
      }
    }

    return TvState(
      profiles: profiles,
      activeSession: activeSession,
      masterLockEnabled: settings.masterLockEnabled,
      parentPinSet: settings.parentPin.isNotEmpty,
      remainingByProfile: remainingByProfile,
      usageByProfile: usageByProfile,
      overlayPermissionGranted: overlayPermissionGranted,
    );
  }

  /// Records one usage event for [profileId] (or the app-global id for the
  /// shutdown/powerOn pair) against [at]'s date, defaulting to today.
  Future<void> recordUsageEvent(
    String profileId,
    UsageEventType type, {
    String? detail,
    DateTime? at,
  }) async {
    await db.recordEvent(
      profileId: profileId,
      date: at ?? engine.clock.today(),
      type: type,
      detail: detail,
    );
  }

  Future<Profile> createProfile({
    required String name,
    required String avatar,
    required AllowanceMinutes allowance,
    bool isParent = false,
  }) async {
    final profile = Profile(
      id: randomHex(8),
      name: name,
      avatar: avatar,
      allowance: allowance,
      isParent: isParent,
    );
    await db.upsertProfile(profile);
    return profile;
  }

  /// Applies partial updates; fields left null are untouched. Returns the
  /// updated profile, or null if [id] does not exist.
  Future<Profile?> patchProfile(
    String id, {
    String? name,
    String? avatar,
    AllowanceMinutes? allowance,
    bool? isParent,
  }) async {
    final profiles = await db.allProfiles();
    final current = profiles.where((p) => p.id == id).firstOrNull;
    if (current == null) return null;
    final updated = Profile(
      id: current.id,
      name: name ?? current.name,
      avatar: avatar ?? current.avatar,
      allowance: allowance ?? current.allowance,
      isParent: isParent ?? current.isParent,
    );
    await db.upsertProfile(updated);
    return updated;
  }

  /// Adds [addSeconds] of session time on top of the profile's current
  /// remaining (full allowance if no session exists yet) and re-arms the
  /// fired thresholds below the new remaining. Returns the new remaining, or
  /// null if the profile does not exist.
  Future<int?> addTime(String profileId, int addSeconds) async {
    final profile = await _profile(profileId);
    if (profile == null) return null;
    final today = engine.clock.today();
    final session = await db.sessionForProfile(profileId, today);
    final newRemaining = (session?.remainingSeconds ?? profile.allowance.minutes * 60) + addSeconds;
    await db.saveSession(SessionState(
      profileId: profileId,
      date: today,
      remainingSeconds: newRemaining,
      active: session?.active ?? false,
    ));
    rearmThresholds(profileId, newRemaining);
    await recordUsageEvent(
      profileId,
      UsageEventType.addTime,
      detail: '$addSeconds',
      at: today,
    );
    return newRemaining;
  }

  /// Overwrites the profile's remaining time for today. Returns the value
  /// written (also re-arms fired thresholds, same rule as [addTime]), or
  /// null if the profile does not exist.
  Future<int?> overrideRemaining(String profileId, int remainingSeconds) async {
    final profile = await _profile(profileId);
    if (profile == null) return null;
    final today = engine.clock.today();
    final session = await db.sessionForProfile(profileId, today);
    await db.saveSession(SessionState(
      profileId: profileId,
      date: today,
      remainingSeconds: remainingSeconds,
      active: session?.active ?? false,
    ));
    rearmThresholds(profileId, remainingSeconds);
    await recordUsageEvent(
      profileId,
      UsageEventType.overrideTime,
      detail: '$remainingSeconds',
      at: today,
    );
    return remainingSeconds;
  }

  /// Applies the master lock to every current profile's today-session.
  ///
  /// Locking preserves remaining times and marks every session inactive,
  /// recording WHICH profile had the day's active session in
  /// [Settings.lockedActiveProfileId]. Unlocking reactivates only that
  /// locked-away session — the single-active invariant holds across a lock
  /// cycle; when no session was active at lock time, unlocking restores
  /// none.
  Future<void> setMasterLock(bool enabled) async {
    final profiles = await db.allProfiles();
    final today = engine.clock.today();
    final settings = await db.getSettings();
    if (enabled) {
      String? lockedActiveProfileId;
      for (final p in profiles) {
        final session = await db.sessionForProfile(p.id, today);
        if (session == null) continue;
        if (session.active && lockedActiveProfileId == null) {
          lockedActiveProfileId = p.id;
        }
        await db.saveSession(
          engine.applyMasterLock(session, locked: true, allowance: p.allowance),
        );
      }
      await db.saveSettings(Settings(
        parentPin: settings.parentPin,
        token: settings.token,
        masterLockEnabled: true,
        lockedActiveProfileId: lockedActiveProfileId,
      ));
      await recordUsageEvent(
          EleenDatabase.appGlobalProfileId, UsageEventType.masterLockOn);
      return;
    }
    // Unlock: restore only the locked-away active session, if there was
    // one. Every other session stays inactive.
    final lockedId = settings.lockedActiveProfileId;
    if (lockedId != null) {
      final profile = profiles.where((p) => p.id == lockedId).firstOrNull;
      final session =
          profile == null ? null : await db.sessionForProfile(profile.id, today);
      if (profile != null && session != null) {
        await db.saveSession(engine.applyMasterLock(
          session,
          locked: false,
          allowance: profile.allowance,
        ));
      }
    }
    await db.saveSettings(Settings(
      parentPin: settings.parentPin,
      token: settings.token,
      masterLockEnabled: false,
    ));
    await recordUsageEvent(
        EleenDatabase.appGlobalProfileId, UsageEventType.masterLockOff);
  }

  /// Records the shutdown -> powerOn event pair for the PREVIOUS run of the
  /// app, closing out its usage at the last persisted tick marker (the tick
  /// loop persists [EleenDatabase.lastTickUptimeMsKey] every tick, so
  /// nothing is added past it — the recorded usedSeconds are final).
  ///
  /// No-op on the very first run (no marker) and at most once per
  /// coordinator instance. The pair is recorded against
  /// [EleenDatabase.appGlobalProfileId]; when the monotonic clock survived
  /// (same-boot restart) the shutdown event's detail carries the elapsed
  /// down-time, otherwise it notes the clock reset (reboot).
  Future<void> recoverShutdown() async {
    if (_recoveryRecorded) return;
    _recoveryRecorded = true;
    final marker =
        await db.getMetaInt(EleenDatabase.lastTickUptimeMsKey);
    if (marker == null) return;
    final nowMs = engine.clock.nowMs();
    final downMs = nowMs >= marker ? nowMs - marker : null;
    await recordUsageEvent(
      EleenDatabase.appGlobalProfileId,
      UsageEventType.shutdown,
      detail: downMs == null
          ? 'monotonic clock reset (reboot); lastTickUptimeMs=$marker'
          : 'elapsedDownMs=$downMs',
    );
    await recordUsageEvent(
      EleenDatabase.appGlobalProfileId,
      UsageEventType.powerOn,
      detail: 'lastTickUptimeMs=$marker',
    );
  }

  /// Whether [recoverShutdown] already ran for this coordinator instance.
  bool _recoveryRecorded = false;

  Future<Profile?> _profile(String id) async =>
      (await db.allProfiles()).where((p) => p.id == id).firstOrNull;

  /// Sets or clears the parent PIN directly in the settings (the db is the
  /// source of truth). An empty [pin] clears it — from then on no PIN gate
  /// applies anywhere (server `_checkPin` skips, TV prompts are bypassed).
  /// Used by the TV-side PIN management UI; the HTTP route (`PUT /api/pin`)
  /// does its own validation and keeps the API shape unchanged.
  Future<void> setParentPin(String pin) async {
    final settings = await db.getSettings();
    await db.saveSettings(Settings(
      parentPin: pin,
      token: settings.token,
      masterLockEnabled: settings.masterLockEnabled,
      lockedActiveProfileId: settings.lockedActiveProfileId,
    ));
  }
}

/// The LAN HTTP server. Route dispatch is the only HTTP-specific logic here;
/// all domain behavior lives in [EngineCoordinator].
class EleenServer {
  EleenServer({required EngineCoordinator coordinator,
      Set<String>? pendingNonces})
      : coordinator = coordinator,
        _pendingNonces = pendingNonces ?? {};

  final EngineCoordinator coordinator;
  final Set<String> _pendingNonces;
  HttpServer? _server;

  /// Single-use pairing nonces currently accepted by `POST /api/pair`.
  /// The pairing screen registers each nonce it encodes into a payload.
  void registerNonce(String nonce) => _pendingNonces.add(nonce);

  int get port => _server?.port ?? (throw StateError('server not started'));

  Future<void> start({required InternetAddress address, int port = 8477}) async {
    if (_server != null) throw StateError('server already started');
    _server = await HttpServer.bind(address, port);
    _server!.listen((request) {
      _handle(request).catchError((Object e) {
        // Last-resort: nothing was written yet if we get here via onError.
        try {
          request.response.statusCode = HttpStatus.internalServerError;
          request.response.close();
        } catch (_) {}
      });
    });
  }

  Future<void> stop() async {
    final server = _server;
    _server = null;
    await server?.close(force: true);
  }

  Future<void> _handle(HttpRequest request) async {
    int status;
    Object body;
    try {
      (status, body) = await _route(request);
    } on _ApiError catch (e) {
      (status, body) = (e.status, {'error': e.message});
    } catch (e) {
      (status, body) = (500, {'error': 'internal error'});
    }
    request.response.statusCode = status;
    request.response.headers.contentType = ContentType.json;
    request.response.write(jsonEncode(body));
    await request.response.close();
  }

  Future<(int, Object)> _route(HttpRequest request) async {
    final path = request.uri.path;
    final method = request.method;

    if (method == 'POST' && path == '/api/pair') return _pair(request);

    // Every route below requires the paired bearer token.
    final settings = await coordinator.db.getSettings();
    final token = _bearerToken(request);
    if (token == null || settings.token == null || token != settings.token) {
      throw _ApiError(HttpStatus.unauthorized, 'missing or invalid token');
    }

    if (method == 'GET' && path == '/api/state') return _state();
    if (method == 'POST' && path == '/api/profiles') return _createProfile(request);
    if (method == 'PATCH' && path.startsWith('/api/profiles/')) {
      return _patchProfile(request, path.substring('/api/profiles/'.length));
    }
    if (method == 'POST' && path == '/api/time') return _addTime(request);
    if (method == 'PUT' && path.startsWith('/api/time/')) {
      return _overrideTime(request, path.substring('/api/time/'.length));
    }
    if (method == 'POST' && path == '/api/lock') return _lock(request);
    if (method == 'PUT' && path == '/api/pin') return _setPin(request);

    throw _ApiError(HttpStatus.notFound, 'not found');
  }

  Future<(int, Object)> _pair(HttpRequest request) async {
    final body = await _jsonBody(request);
    final nonce = body['nonce'];
    // Set.remove returns whether the nonce was registered; removing it also
    // enforces single use.
    if (nonce is! String || !_pendingNonces.remove(nonce)) {
      throw _ApiError(HttpStatus.unauthorized, 'invalid nonce');
    }
    final token = randomHex(32);
    final settings = await coordinator.db.getSettings();
    await coordinator.db.saveSettings(Settings(
      parentPin: settings.parentPin,
      token: token,
      masterLockEnabled: settings.masterLockEnabled,
      lockedActiveProfileId: settings.lockedActiveProfileId,
    ));
    return (HttpStatus.ok, {'token': token});
  }

  Future<(int, Object)> _state() async {
    final st = await coordinator.state();
    return (
      HttpStatus.ok,
      {
        'profiles': [for (final p in st.profiles) _profileJson(p)],
        'activeProfileId': st.activeSession?.profileId,
        'remainingByProfile': st.remainingByProfile,
        'masterLockEnabled': st.masterLockEnabled,
        'parentPinSet': st.parentPinSet,
        'overlayPermissionGranted': st.overlayPermissionGranted,
        // v1.1 D: daily usage per profile (history capped at 14 days).
        'usage': {
          for (final entry in st.usageByProfile.entries)
            entry.key: {
              'todaySeconds': entry.value.todaySeconds,
              'history': [
                for (final day in entry.value.history)
                  {
                    'date': DayUsage.wire(day.date),
                    'seconds': day.seconds,
                  },
              ],
            },
        },
      }
    );
  }

  Future<(int, Object)> _createProfile(HttpRequest request) async {
    final body = await _jsonBody(request);
    await _checkPin(body);
    final allowance = _allowance(body);
    final profile = await coordinator.createProfile(
      name: _string(body, 'name'),
      avatar: _string(body, 'avatar'),
      allowance: allowance,
      isParent: _optionalBool(body, 'isParent') ?? false,
    );
    return (HttpStatus.ok, _profileJson(profile));
  }

  Future<(int, Object)> _patchProfile(HttpRequest request, String id) async {
    final body = await _jsonBody(request);
    await _checkPin(body);
    final allowance = body.containsKey('allowanceMinutes') ? _allowance(body) : null;
    final updated = await coordinator.patchProfile(
      id,
      name: body.containsKey('name') ? _string(body, 'name') : null,
      avatar: body.containsKey('avatar') ? _string(body, 'avatar') : null,
      allowance: allowance,
      isParent: _optionalBool(body, 'isParent'),
    );
    if (updated == null) throw _ApiError(HttpStatus.notFound, 'unknown profile');
    return (HttpStatus.ok, _profileJson(updated));
  }

  Future<(int, Object)> _addTime(HttpRequest request) async {
    final body = await _jsonBody(request);
    await _checkPin(body);
    final profileId = _string(body, 'profileId');
    final addSeconds = _int(body, 'addSeconds');
    if (addSeconds < 0) {
      throw _ApiError(HttpStatus.badRequest, 'addSeconds must not be negative');
    }
    final remaining = await coordinator.addTime(profileId, addSeconds);
    if (remaining == null) throw _ApiError(HttpStatus.notFound, 'unknown profile');
    return (HttpStatus.ok, {'profileId': profileId, 'remainingSeconds': remaining});
  }

  Future<(int, Object)> _overrideTime(HttpRequest request, String id) async {
    final body = await _jsonBody(request);
    await _checkPin(body);
    final remainingSeconds = _int(body, 'remainingSeconds');
    if (remainingSeconds < 0) {
      throw _ApiError(
          HttpStatus.badRequest, 'remainingSeconds must not be negative');
    }
    final remaining = await coordinator.overrideRemaining(id, remainingSeconds);
    if (remaining == null) throw _ApiError(HttpStatus.notFound, 'unknown profile');
    return (HttpStatus.ok, {'profileId': id, 'remainingSeconds': remaining});
  }

  Future<(int, Object)> _lock(HttpRequest request) async {
    final body = await _jsonBody(request);
    await _checkPin(body);
    final enabled = body['enabled'];
    if (enabled is! bool) throw _ApiError(HttpStatus.badRequest, 'enabled must be a bool');
    await coordinator.setMasterLock(enabled);
    return (HttpStatus.ok, {'masterLockEnabled': enabled});
  }

  /// Sets or changes the parent PIN (`PUT /api/pin`). Token-authenticated
  /// like every other route, but NOT PIN-gated in the usual sense — this is
  /// the provisioning route:
  ///
  /// - No PIN set yet (fresh install): `pin` alone is accepted, so the
  ///   pairing phone can provision the PIN without knowing a current one.
  /// - PIN already set: `currentPin` must match, or the same 403 as every
  ///   other PIN-gated route.
  /// - `pin` must be a non-empty string of exactly 4 digits, else 400.
  Future<(int, Object)> _setPin(HttpRequest request) async {
    final body = await _jsonBody(request);
    final newPin = body['pin'];
    if (newPin is! String ||
        newPin.isEmpty ||
        newPin.length < 4 ||
        newPin.length > 4) {
      throw _ApiError(
          HttpStatus.badRequest, 'pin must be exactly 4 characters');
    }
    final settings = await coordinator.db.getSettings();
    if (settings.parentPin.isNotEmpty) {
      final currentPin = body['currentPin'];
      if (currentPin is! String || currentPin != settings.parentPin) {
        throw _ApiError(HttpStatus.forbidden, 'invalid pin');
      }
    }
    await coordinator.db.saveSettings(Settings(
      parentPin: newPin,
      token: settings.token,
      masterLockEnabled: settings.masterLockEnabled,
      lockedActiveProfileId: settings.lockedActiveProfileId,
    ));
    return (HttpStatus.ok, {'parentPinSet': true});
  }

  // --- helpers ---

  /// The PIN gate every mutating route runs. Backward-compatible contract:
  /// while NO parent PIN is set (`Settings.parentPin` empty — the fresh
  /// install shape) the check is skipped and any `pin` value (or none) is
  /// accepted; once a PIN is set, a wrong or missing `pin` is a 403.
  Future<void> _checkPin(Map<String, dynamic> body) async {
    final settings = await coordinator.db.getSettings();
    if (settings.parentPin.isEmpty) return;
    if (body['pin'] is! String || body['pin'] != settings.parentPin) {
      throw _ApiError(HttpStatus.forbidden, 'invalid pin');
    }
  }

  String? _bearerToken(HttpRequest request) {
    final header = request.headers.value(HttpHeaders.authorizationHeader);
    if (header == null) return null;
    final match = RegExp(r'^Bearer (.+)$').firstMatch(header);
    return match?.group(1);
  }

  Future<Map<String, dynamic>> _jsonBody(HttpRequest request) async {
    String text;
    try {
      text = await utf8.decoder.bind(request).join();
    } on FormatException {
      throw _ApiError(HttpStatus.badRequest, 'body is not valid UTF-8');
    }
    if (text.isEmpty) throw _ApiError(HttpStatus.badRequest, 'missing JSON body');
    final Object decoded;
    try {
      decoded = jsonDecode(text);
    } on FormatException {
      throw _ApiError(HttpStatus.badRequest, 'invalid JSON body');
    }
    if (decoded is! Map<String, dynamic>) {
      throw _ApiError(HttpStatus.badRequest, 'body must be a JSON object');
    }
    return decoded;
  }

  AllowanceMinutes _allowance(Map<String, dynamic> body) {
    final minutes = _int(body, 'allowanceMinutes');
    final allowance = AllowanceMinutes.fromMinutes(minutes);
    if (allowance == null) {
      throw _ApiError(HttpStatus.badRequest, 'invalid allowanceMinutes');
    }
    return allowance;
  }

  String _string(Map<String, dynamic> body, String key) {
    final value = body[key];
    if (value is! String) throw _ApiError(HttpStatus.badRequest, '$key must be a string');
    return value;
  }

  int _int(Map<String, dynamic> body, String key) {
    final value = body[key];
    if (value is! int) throw _ApiError(HttpStatus.badRequest, '$key must be an int');
    return value;
  }

  /// The bool [key] from [body], or null when the key is absent. A present
  /// but non-bool value is a 400.
  bool? _optionalBool(Map<String, dynamic> body, String key) {
    if (!body.containsKey(key)) return null;
    final value = body[key];
    if (value is! bool) {
      throw _ApiError(HttpStatus.badRequest, '$key must be a bool');
    }
    return value;
  }
}

Map<String, Object> _profileJson(Profile p) => {
      'id': p.id,
      'name': p.name,
      'avatar': p.avatar,
      'allowanceMinutes': p.allowance.minutes,
      'isParent': p.isParent,
    };

/// HTTP-level failure with a status code, translated to a JSON error body.
class _ApiError implements Exception {
  _ApiError(this.status, this.message);

  final int status;
  final String message;
}
